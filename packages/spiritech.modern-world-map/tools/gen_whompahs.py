#!/usr/bin/env python3
"""Extract the Rubi-Ka whompah network from the client database (for route planning).

Statels live in cd_image/rdb.db table rdb_1000026, one record per playfield (id = playfield).
A zone-to-zone link statel contains the marker 00 01 86 a1 followed by big-endian
<u16 index><u16 destination playfield>. The statel header before it is
<u16 type> 00 00 <u16 playfield LE> <idx> c0, followed (within ~40 bytes) by the playfield
as u32 LE and the position as three LE floats x, y, z (local playfield coordinates).
Only links between zones connected to Newland City are kept (Rubi-Ka; Shadowlands portals
use the same marker). Every Rubi-Ka link has a matching link back.

Also emits, per Rubi-Ka planet map (textures/PlanetMap/*/*.txt with a CoordsFile), the
offsets of the whompah zones (coords.xml: global = offset + local * scale) and each level's
MapRect, used to carry a measured projection from one map level to another.

Usage: gen_whompahs.py [client_dir] > ../whompahs.lua
"""
import re, sqlite3, struct, sys, os, collections

client = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Games/spiritech/client")
db = sqlite3.connect(f"file:{client}/cd_image/rdb.db?mode=ro", uri=True)
coords = open(f"{client}/cd_image/textures/PlanetMap/MapCoordinates.xml").read()
outdoor = {int(i) for i in re.findall(r'<Playfield id="(\d+)"', coords)}
names = {}
for pid, blob in db.execute("select id, data from rdb_1000001"):
    raw = bytes(blob)[8:72]
    names[pid] = raw.split(b"\0", 1)[0].decode("latin-1")

links = []
for pid, blob in db.execute("select id, data from rdb_1000026"):
    if pid not in outdoor:
        continue
    d = bytes(blob)
    own = struct.pack("<H", pid)
    for m in re.finditer(rb"\x00\x01\x86\xa1", d):
        j = m.start()
        _, dest = struct.unpack_from(">HH", d, j + 4)
        if dest not in outdoor or dest == pid:
            continue
        lo = max(0, j - 400)
        headers = list(re.finditer(rb"..\x00\x00" + re.escape(own) + rb".\xc0", d[lo:j], re.S))
        if not headers:
            continue
        hdr = lo + headers[-1].start()
        p = d.find(struct.pack("<I", pid), hdr + 8, hdr + 40)
        if p < 0:
            continue
        x, y, z = struct.unpack_from("<fff", d, p + 4)
        links.append((pid, x, z, dest))

# keep the component containing Newland City (566)
graph = collections.defaultdict(set)
for a, _, _, b in links:
    graph[a].add(b); graph[b].add(a)
seen, todo = {566}, [566]
while todo:
    for n in graph[todo.pop()]:
        if n not in seen:
            seen.add(n); todo.append(n)
links = sorted(l for l in links if l[0] in seen and l[3] in seen)
pairs = {(a, b) for a, _, _, b in links}
oneway = [(a, b) for a, b in pairs if (b, a) not in pairs]
if oneway:
    print("-- WARNING one-way links:", oneway, file=sys.stderr)

zones = sorted({a for a, _, _, _ in links})

def find_ci(base, rel):
    """Resolve a path case-insensitively (the map files were written on Windows)."""
    path = base
    for part in rel.replace("\\", "/").split("/"):
        match = [e for e in os.listdir(path) if e.lower() == part.lower()] if os.path.isdir(path) else []
        if not match:
            return None
        path = os.path.join(path, match[0])
    return path

maps = []
base = f"{client}/cd_image/textures/PlanetMap"
for folder in sorted(os.listdir(base)):
    if not os.path.isdir(f"{base}/{folder}"):
        continue
    for txt in sorted(os.listdir(f"{base}/{folder}")):
        if not txt.endswith(".txt"):
            continue
        text = open(f"{base}/{folder}/{txt}", errors="replace").read()
        name = re.search(r'^Name\s+"([^"]*)"', text, re.M)
        cfile = re.search(r"^CoordsFile\s+(\S+)", text, re.M)
        if not name or not cfile or not re.search(r"^Type\s+Rubika", text, re.M):
            continue
        path = find_ci(base, cfile.group(1))
        if not path:
            continue
        xml = open(path).read()
        offs = {int(i): (float(x), float(xs), float(z), float(zs)) for i, x, xs, z, zs in re.findall(
            r'id="(\d+)"[^>]*?x="([-\d.]+)" xscale="([\d.]+)" z="([-\d.]+)" zscale="([\d.]+)"', xml)}
        if not all(z in offs for z in zones):
            continue
        rects = [tuple(int(v) for v in r) for r in re.findall(r"^MapRect\s+(\d+)\s+(\d+)\s+(\d+)\s+(\d+)", text, re.M)]
        maps.append((name.group(1), offs, rects))

print("-- Rubi-Ka whompahs, generated by tools/gen_whompahs.py from the client database.")
print("-- { playfield, local x, local z, destination playfield }")
print("WHOMPAHS = {")
for a, x, z, b in links:
    print(f"\t{{ {a}, {x:.1f}, {z:.1f}, {b} }}, -- {names.get(a, a)} -> {names.get(b, b)}")
print("}")
# Same map name from two index files: keep the offsets, drop rects that disagree.
merged = {}
for name, offs, rects in maps:
    if name in merged:
        if merged[name][1] != rects:
            merged[name] = (merged[name][0], [])
    else:
        merged[name] = (offs, rects)
maps = [(name, offs, rects) for name, (offs, rects) in merged.items()]

print()
print("-- Per planet map: zone offsets { x, xscale, z, zscale } and each level's MapRect.")
print("WHOMPAH_MAPS = {")
for name, offs, rects in maps:
    print(f'\t["{name}"] = {{')
    print("\t\tzones = {")
    for z in zones:
        x, xs, zz, zs = offs[z]
        print(f"\t\t\t[{z}] = {{ {x:g}, {xs:g}, {zz:g}, {zs:g} }},")
    print("\t\t},")
    print("\t\trects = { " + ", ".join("{ %d, %d, %d, %d }" % r for r in rects) + " }, -- per level; empty = unknown")
    print("\t},")
print("}")
