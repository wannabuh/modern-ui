#!/usr/bin/env python3
"""Generate implant / symbiant stat modifiers for the Modern Inventory from the item database.

Reads cd_image/rdb.db (table rdb_1000020 = items). Implants and symbiants are item class 3
(attribute 76). Their stat bonuses are "Modify" functions (53045) in the on-wear event (14):

    chunk 2, event 14, 1009-encoded function count, then per function:
        53045, ?, ?, requirement count, (stat, value, op) * count,
        tick count, tick interval, target, 9, stat, amount

Many cluster implants share one name: "Eye Implant: Rifle, Shiny" exists for every
combination of the bright/faded clusters (456 records). The name only reveals the named
cluster, so per name + QL we keep the modifiers common to ALL records with that name and
flag when some record has more (the row then shows "+?"). Writes ONE file, lua/itemmods.lua
(each .lua under lua/ is a module, and a package may register at most 64 modules in total;
splitting this per letter like itemreqs pushed every dependent package over that limit):

    return { ["Item Name"] = { more = true|nil, {ql, "stat:amount,stat:amount"}, ... } }

Re-run after game updates:

    python3 gen_itemmods.py ~/Games/spiritech/client/cd_image/rdb.db
"""
import os, sqlite3, struct, sys, collections

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_itemreqs import attributes, name_of  # same record layout

DB = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Games/spiritech/client/cd_image/rdb.db")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lua")
ITEM_CLASS, IMPLANT = 76, 3
ON_WEAR, MODIFY = 14, 53045


def modifiers(b, start):
    """[(stat, amount), ...] from the on-wear event, or [] if there is none."""
    n = (len(b) - start) // 4
    ints = struct.unpack_from("<%di" % n, b, start)
    out = []
    # Events chunk (key 2) normally starts right after the description.
    if len(ints) < 3 or ints[0] != 2 or ints[2] % 1009:
        return out
    p, events = 1, 1  # implants carry a single (on-wear) event here
    event, count = ints[1], ints[2] // 1009 - 1
    if event != ON_WEAR:
        return out
    p = 3
    for _ in range(count):
        if p + 4 > len(ints) or ints[p] != MODIFY:
            break  # another function type: its argument layout differs, stop here
        q = p + 4 + 3 * ints[p + 3]  # skip its requirements
        if q + 6 > len(ints) or ints[q + 3] != 9:
            break
        out.append((ints[q + 4], ints[q + 5]))
        p = q + 6
    return out


def main():
    db = sqlite3.connect(DB)
    records = collections.defaultdict(lambda: collections.defaultdict(list))  # name -> ql -> [mods]
    for _item_id, b in db.execute("select id, data from rdb_1000020"):
        if not b or len(b) < 40:
            continue
        try:
            attrs, p = attributes(b)
            if attrs.get(ITEM_CLASS) != IMPLANT:
                continue
            name, chunks = name_of(b, p)
            if not name:
                continue
            mods = modifiers(b, chunks)
        except struct.error:
            continue
        records[name][attrs.get(54, 1)].append(mods)

    lines = []
    total = ambiguous = 0
    for name, by_ql in records.items():
        points, more = [], False
        for ql in sorted(by_ql):
            sets = [set(m) for m in by_ql[ql]]
            common = set.intersection(*sets)
            if any(s != common for s in sets):
                more = True
            if common:
                # biggest bonus first (the shiny cluster on cluster-built implants)
                ordered = sorted(common, key=lambda sv: (-sv[1], sv[0]))
                points.append('{%d,"%s"}' % (ql, ",".join("%d:%d" % sv for sv in ordered)))
        if not points:
            continue
        total += 1
        ambiguous += more
        esc = name.replace("\\", "\\\\").replace('"', '\\"')
        lines.append('["%s"]={%s%s}' % (esc, "more=true," if more else "", ",".join(points)))

    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "itemmods.lua"), "w", encoding="latin-1") as f:
        f.write("-- Generated by tools/gen_itemmods.py from the client's item database. Do not edit.\n")
        f.write("return {\n" + ",\n".join(sorted(lines)) + "\n}\n")
    print(f"{total} implant/symbiant names with modifiers ({ambiguous} with unknown extra clusters)")


if __name__ == "__main__":
    main()
